#!/usr/bin/env python3
"""Refresh CSS references and produce a self-contained, offline HTML app.
Usage: python3 tools/build_offline.py [folder containing index.html]
No dependencies, browser automation, network or build service required.
"""
from pathlib import Path
import base64, hashlib, io, json, mimetypes, re, sys, zipfile

root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
assert (root / 'index.html').exists(), 'Run from the project or pass its asset folder.'

def data_uri(path):
    mime = {'.svg':'image/svg+xml','.ttf':'font/ttf'}.get(path.suffix, mimetypes.guess_type(path.name)[0] or 'application/octet-stream')
    return 'data:' + mime + ';base64,' + base64.b64encode(path.read_bytes()).decode()

def inline_css(path):
    text = path.read_text()
    text = re.sub(r'@import\s+url\([\'"]([^\'"]+)[\'"]\);', lambda m: inline_css((path.parent / m[1]).resolve()), text)
    def replace_url(m):
        ref = m[1].strip('"\'')
        if ref.startswith(('data:', 'https:', 'http:', '#')):
            return m[0]
        return 'url("' + data_uri((path.parent / ref).resolve()) + '")'
    return re.sub(r'url\(([^)]+)\)', replace_url, text)

def script_json(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')

resources = {'css':(root/'kiddash.css').read_text(), 'responsive':(root/'responsive.css').read_text()}
(root/'guide-resources.js').write_text('/* Generated by tools/build_offline.py; refresh after CSS edits. */\nwindow.KIDDASH_RESOURCES='+script_json(resources)+';\n')

def source_files():
    for p in sorted(root.rglob('*')):
        rel = p.relative_to(root)
        if not p.is_file() or any(part.startswith('.') for part in rel.parts):
            continue
        if p.name in ('kiddash-style-guide-offline.html','kiddash-style-guide.zip') or p.suffix == '.zip':
            continue
        yield p, rel

def make_zip(include_offline=False):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as archive:
        for p, rel in source_files():
            archive.writestr(str(rel), p.read_bytes())
        if include_offline:
            archive.writestr('kiddash-style-guide-offline.html',(root/'kiddash-style-guide-offline.html').read_bytes())
    return buffer.getvalue()

html = (root/'index.html').read_text()
# Keep cached scripts and styles in sync with the published page structure.
for name in ('guide.css', 'guide-resources.js', 'guide.js', 'library.js'):
    version = hashlib.sha256((root/name).read_bytes()).hexdigest()[:12]
    html = re.sub(r'((?:src|href)="' + re.escape(name) + r')(?:\?[^"]*)?"',
                  lambda m: m[1] + '?v=' + version + '"', html)
(root/'index.html').write_text(html)
html = re.sub(r'<link rel="stylesheet" href="guide\.css(?:\?[^"]*)?">', lambda m: '<style>'+inline_css(root/'guide.css')+'</style>', html)
html = re.sub(r'<script src="(?:guide-resources|guide|library)\.js(?:\?[^"]*)?" defer></script>', '', html)
html = re.sub(r'<div class="download-row" id="offline-download-row">.*?</a></div>','',html,flags=re.S)
html = re.sub(r'src="(assets/[^\"]+)"',lambda m:'src="'+data_uri(root/m[1])+'"',html)
html = html.replace('<title>Kiddash · Style Guide</title>','<title>Kiddash · Offline Style Guide</title>')
assets = {p.name:data_uri(p) for p in (root/'assets').glob('*.svg')}
overview = (root/'overview.html').read_text().replace('<link rel="stylesheet" href="kiddash.css">','<style>'+inline_css(root/'kiddash.css')+'</style>')
overview = re.sub(r'src="(assets/[^\"]+)"',lambda m:'src="'+data_uri(root/m[1])+'"',overview)
overview = overview.replace("new URL('index.html',location.href)","new URL('kiddash-style-guide-offline.html',location.href)")
downloads = {}
for name, content, mime in [
    ('kiddash.css',(root/'kiddash.css').read_bytes(),'text/css'),
    ('guide.css',(root/'guide.css').read_bytes(),'text/css'),
    ('responsive.css',(root/'responsive.css').read_bytes(),'text/css'),
    ('assets/kiddash-logo.svg',(root/'assets/kiddash-logo.svg').read_bytes(),'image/svg+xml'),
    ('overview.html',overview.encode(),'text/html'),
    ('kiddash-style-guide.zip',make_zip(),'application/zip'),
]:
    downloads[name]={'type':mime,'data':base64.b64encode(content).decode()}
script = 'window.KIDDASH_RESOURCES='+script_json(resources)+';\nwindow.KIDDASH_ASSETS='+script_json(assets)+';\nwindow.KIDDASH_DOWNLOADS='+script_json(downloads)+';\n'+(root/'guide.js').read_text()+'\n;\n'+(root/'library.js').read_text()
html = html.replace('</body>','<script>'+script+'</script></body>')
(root/'kiddash-style-guide-offline.html').write_text(html)
(root/'kiddash-style-guide.zip').write_bytes(make_zip(include_offline=True))
print('Built offline HTML:', len(html.encode()), 'bytes')
print('Built source ZIP:', (root/'kiddash-style-guide.zip').stat().st_size, 'bytes')
